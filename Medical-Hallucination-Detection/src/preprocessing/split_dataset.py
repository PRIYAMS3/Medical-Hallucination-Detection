"""Reproducible stratified train/validation/test splitting for MedHallu.

This module creates fixed dataset splits for all future experiments. It does
not tokenize text, build features, train models, or modify the original
processed dataset.
"""

from __future__ import annotations

import argparse
import json
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import pandas as pd
from sklearn.model_selection import train_test_split

from src.utils.config import Config, load_config
from src.utils.logging import setup_logging


LOGGER = logging.getLogger(__name__)
DEFAULT_CONFIG_PATH = Path("configs/config.yaml")
SPLIT_NAMES = ("train", "validation", "test")


@dataclass(frozen=True)
class SplitConfig:
    """Configuration values required for deterministic dataset splitting."""

    train_size: float
    validation_size: float
    test_size: float
    random_seed: int
    stratify_column: str
    splits_dir: Path
    train_file_name: str
    validation_file_name: str
    test_file_name: str


@dataclass(frozen=True)
class SplitValidationResult:
    """Validation checks for generated dataset splits."""

    total_samples_match: bool
    no_missing_rows: bool
    no_overlap: bool
    duplicate_rows_across_splits: int
    original_samples: int
    split_samples: int


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments for split generation."""
    parser = argparse.ArgumentParser(
        description="Create reproducible MedHallu train/validation/test splits."
    )
    parser.add_argument(
        "--config",
        type=Path,
        default=DEFAULT_CONFIG_PATH,
        help="Path to the YAML configuration file.",
    )
    return parser.parse_args()


def initialize_logging(config: Config) -> logging.Logger:
    """Initialize logging from project configuration."""
    logging_config = config.get("logging", {})
    paths_config = config.get("paths", {})
    return setup_logging(
        log_dir=paths_config.get("logs_dir", "outputs/logs"),
        file_name="split_dataset.log",
        level=logging_config.get("level", "INFO"),
        log_format=logging_config.get(
            "format", "%(asctime)s | %(levelname)s | %(name)s | %(message)s"
        ),
        date_format=logging_config.get("date_format", "%Y-%m-%d %H:%M:%S"),
    )


def get_split_config(config: Config) -> SplitConfig:
    """Extract and validate dataset split configuration."""
    split_config = config.get("dataset_split", {})
    result = SplitConfig(
        train_size=float(split_config.get("train_size", 0.70)),
        validation_size=float(split_config.get("validation_size", 0.15)),
        test_size=float(split_config.get("test_size", 0.15)),
        random_seed=int(split_config.get("random_seed", 42)),
        stratify_column=str(split_config.get("stratify_column", "Difficulty Level")),
        splits_dir=Path(split_config.get("splits_dir", "data/splits")),
        train_file_name=str(split_config.get("train_file_name", "train.csv")),
        validation_file_name=str(
            split_config.get("validation_file_name", "validation.csv")
        ),
        test_file_name=str(split_config.get("test_file_name", "test.csv")),
    )

    ratio_sum = result.train_size + result.validation_size + result.test_size
    if abs(ratio_sum - 1.0) > 1e-8:
        raise ValueError(f"Split ratios must sum to 1.0, got {ratio_sum:.6f}.")

    for split_name, split_size in (
        ("train_size", result.train_size),
        ("validation_size", result.validation_size),
        ("test_size", result.test_size),
    ):
        if split_size <= 0 or split_size >= 1:
            raise ValueError(f"{split_name} must be between 0 and 1.")

    return result


def processed_dataset_path(config: Config) -> Path:
    """Return the configured processed dataset CSV path."""
    dataset_config = config.get("dataset", {})
    return Path(dataset_config.get("processed_data_dir", "data/processed")) / str(
        dataset_config.get("processed_file_name", "medhallu_processed.csv")
    )


def load_processed_dataset(config: Config) -> pd.DataFrame:
    """Load the processed MedHallu dataset generated by ``dataset.py``."""
    path = processed_dataset_path(config)
    if not path.exists():
        raise FileNotFoundError(
            f"Processed dataset not found at {path}. Run dataset.py first."
        )

    LOGGER.info("Loading processed dataset from %s", path)
    dataframe = pd.read_csv(path)
    LOGGER.info("Loaded %s samples and %s columns.", *dataframe.shape)
    return dataframe


def create_stratified_splits(
    dataframe: pd.DataFrame, split_config: SplitConfig
) -> dict[str, pd.DataFrame]:
    """Create reproducible stratified train/validation/test splits."""
    if split_config.stratify_column not in dataframe.columns:
        raise ValueError(
            f"Stratify column not found: {split_config.stratify_column}"
        )

    LOGGER.info(
        "Creating stratified splits with ratios train=%.2f, validation=%.2f, "
        "test=%.2f and seed=%s.",
        split_config.train_size,
        split_config.validation_size,
        split_config.test_size,
        split_config.random_seed,
    )
    train_df, temporary_df = train_test_split(
        dataframe,
        train_size=split_config.train_size,
        random_state=split_config.random_seed,
        stratify=dataframe[split_config.stratify_column],
        shuffle=True,
    )

    relative_test_size = split_config.test_size / (
        split_config.validation_size + split_config.test_size
    )
    validation_df, test_df = train_test_split(
        temporary_df,
        test_size=relative_test_size,
        random_state=split_config.random_seed,
        stratify=temporary_df[split_config.stratify_column],
        shuffle=True,
    )

    return {
        "train": train_df.reset_index(drop=True),
        "validation": validation_df.reset_index(drop=True),
        "test": test_df.reset_index(drop=True),
    }


def save_splits(splits: dict[str, pd.DataFrame], split_config: SplitConfig) -> None:
    """Save train, validation, and test splits to configured CSV paths."""
    split_config.splits_dir.mkdir(parents=True, exist_ok=True)
    output_files = {
        "train": split_config.train_file_name,
        "validation": split_config.validation_file_name,
        "test": split_config.test_file_name,
    }

    for split_name, dataframe in splits.items():
        output_path = split_config.splits_dir / output_files[split_name]
        dataframe.to_csv(output_path, index=False)
        LOGGER.info("Saved %s split with %s samples to %s", split_name, len(dataframe), output_path)


def row_fingerprints(dataframe: pd.DataFrame) -> pd.Series:
    """Create stable row fingerprints for overlap validation."""
    return pd.util.hash_pandas_object(dataframe, index=False).astype(str)


def validate_splits(
    original: pd.DataFrame, splits: dict[str, pd.DataFrame]
) -> SplitValidationResult:
    """Validate split completeness and absence of overlap."""
    split_samples = sum(len(split) for split in splits.values())
    total_samples_match = split_samples == len(original)
    no_missing_rows = total_samples_match

    split_fingerprints = []
    for split_name in SPLIT_NAMES:
        fingerprints = row_fingerprints(splits[split_name])
        split_fingerprints.append(fingerprints)

    all_fingerprints = pd.concat(split_fingerprints, ignore_index=True)
    duplicate_rows_across_splits = int(all_fingerprints.duplicated().sum())
    no_overlap = duplicate_rows_across_splits == 0

    LOGGER.info("Split validation: total_samples_match=%s", total_samples_match)
    LOGGER.info("Split validation: no_missing_rows=%s", no_missing_rows)
    LOGGER.info("Split validation: no_overlap=%s", no_overlap)

    return SplitValidationResult(
        total_samples_match=total_samples_match,
        no_missing_rows=no_missing_rows,
        no_overlap=no_overlap,
        duplicate_rows_across_splits=duplicate_rows_across_splits,
        original_samples=len(original),
        split_samples=split_samples,
    )


def label_distribution(dataframe: pd.DataFrame, label_column: str) -> dict[str, int]:
    """Return a label distribution dictionary."""
    return {
        str(label): int(count)
        for label, count in dataframe[label_column].value_counts().sort_index().items()
    }


def label_percentages(dataframe: pd.DataFrame, label_column: str) -> dict[str, float]:
    """Return label percentages for a split."""
    counts = dataframe[label_column].value_counts(normalize=True).sort_index()
    return {str(label): float(value * 100) for label, value in counts.items()}


def distribution_drift(
    original: pd.DataFrame,
    split: pd.DataFrame,
    label_column: str,
) -> dict[str, float]:
    """Compute absolute label-percentage drift from the original dataset."""
    original_percentages = label_percentages(original, label_column)
    split_percentages = label_percentages(split, label_column)
    labels = sorted(set(original_percentages) | set(split_percentages))
    return {
        label: abs(split_percentages.get(label, 0.0) - original_percentages.get(label, 0.0))
        for label in labels
    }


def build_split_statistics(
    original: pd.DataFrame,
    splits: dict[str, pd.DataFrame],
    split_config: SplitConfig,
    validation: SplitValidationResult,
) -> dict[str, Any]:
    """Build JSON-serializable split statistics."""
    statistics: dict[str, Any] = {
        "random_seed": split_config.random_seed,
        "split_ratios": {
            "train": split_config.train_size,
            "validation": split_config.validation_size,
            "test": split_config.test_size,
        },
        "total_samples": int(len(original)),
        "stratify_column": split_config.stratify_column,
        "validation_checks": {
            "total_samples_match": validation.total_samples_match,
            "no_missing_rows": validation.no_missing_rows,
            "no_overlap_exists": validation.no_overlap,
            "duplicate_rows_across_splits": validation.duplicate_rows_across_splits,
            "original_samples": validation.original_samples,
            "split_samples": validation.split_samples,
        },
        "splits": {},
    }

    for split_name in SPLIT_NAMES:
        split_df = splits[split_name]
        statistics["splits"][split_name] = {
            "number_of_samples": int(len(split_df)),
            "percentage": float(len(split_df) / len(original) * 100),
            "label_distribution": label_distribution(
                split_df, split_config.stratify_column
            ),
            "label_percentage": label_percentages(
                split_df, split_config.stratify_column
            ),
            "label_percentage_drift_from_full_dataset": distribution_drift(
                original, split_df, split_config.stratify_column
            ),
        }

    return statistics


def save_split_statistics(statistics: dict[str, Any], config: Config) -> Path:
    """Save split statistics as JSON."""
    path = Path(
        config.get("paths", {}).get(
            "split_statistics_json", "outputs/split_statistics.json"
        )
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(statistics, indent=2), encoding="utf-8")
    LOGGER.info("Saved split statistics to %s", path)
    return path


def markdown_distribution(distribution: dict[str, int]) -> str:
    """Format a label distribution dictionary as a markdown table."""
    total = sum(distribution.values())
    lines = ["| Label | Count | Percentage |", "|---|---:|---:|"]
    for label, count in distribution.items():
        percentage = count / total * 100 if total else 0.0
        lines.append(f"| {label} | {count} | {percentage:.2f}% |")
    return "\n".join(lines)


def generate_split_report(statistics: dict[str, Any]) -> str:
    """Generate a markdown report describing split quality."""
    checks = statistics["validation_checks"]
    sections = [
        "# Dataset Split Report",
        "",
        "## Dataset Size",
        "",
        f"- Total samples: `{statistics['total_samples']}`",
        f"- Stratify column: `{statistics['stratify_column']}`",
        f"- Random seed: `{statistics['random_seed']}`",
        "",
        "## Split Sizes",
        "",
        "| Split | Samples | Percentage |",
        "|---|---:|---:|",
    ]

    for split_name in SPLIT_NAMES:
        split_stats = statistics["splits"][split_name]
        sections.append(
            f"| {split_name} | {split_stats['number_of_samples']} | "
            f"{split_stats['percentage']:.2f}% |"
        )

    sections.extend(["", "## Label Distribution by Split", ""])
    for split_name in SPLIT_NAMES:
        sections.extend(
            [
                f"### {split_name.title()}",
                "",
                markdown_distribution(
                    statistics["splits"][split_name]["label_distribution"]
                ),
                "",
            ]
        )

    sections.extend(
        [
            "## Validation Checks",
            "",
            f"- Total samples unchanged: `{checks['total_samples_match']}`",
            f"- No missing rows: `{checks['no_missing_rows']}`",
            f"- No overlap exists: `{checks['no_overlap_exists']}`",
            "- Duplicate rows across splits: "
            f"`{checks['duplicate_rows_across_splits']}`",
            "",
            "## Overlap Confirmation",
            "",
        ]
    )
    if checks["no_overlap_exists"]:
        sections.append("No overlapping rows were detected across splits.")
    else:
        sections.append("Overlapping rows were detected and require investigation.")

    return "\n".join(sections).rstrip() + "\n"


def save_split_report(report: str, config: Config) -> Path:
    """Save the split report as markdown."""
    path = Path(config.get("paths", {}).get("split_report", "outputs/split_report.md"))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(report, encoding="utf-8")
    LOGGER.info("Saved split report to %s", path)
    return path


def main() -> None:
    """Create and validate reproducible MedHallu dataset splits."""
    args = parse_args()
    config = load_config(args.config)
    initialize_logging(config)

    split_config = get_split_config(config)
    dataframe = load_processed_dataset(config)
    splits = create_stratified_splits(dataframe, split_config)
    validation = validate_splits(dataframe, splits)

    if not (
        validation.total_samples_match
        and validation.no_missing_rows
        and validation.no_overlap
    ):
        raise RuntimeError("Dataset split validation failed.")

    save_splits(splits, split_config)
    statistics = build_split_statistics(dataframe, splits, split_config, validation)
    save_split_statistics(statistics, config)
    save_split_report(generate_split_report(statistics), config)
    LOGGER.info("Reproducible dataset split pipeline completed successfully.")


if __name__ == "__main__":
    main()
